// dsh install/uninstall round-trip test — 3 cycles, verify each step.
// Run: node test/dsh-roundtrip.mjs   (or: npm run test:dsh)
//
// WARNING: this drives the real installer against the real dsh home
// (~/.dsh on unix, %LOCALAPPDATA%\dsh on Windows). It snapshots and restores
// cordis.patch.yml and the bundle, but it does create and delete
// profiles/web/node_modules/workled along the way — so it needs a sandbox that
// permits deleting under the dsh home. It is deliberately NOT part of `npm
// test` (which only runs the hermetic unit/install suites).
//
// Plan B (2026-09-05): installDsh copies dsh-plugin/ into the web profile's
// node_modules/workled bundle and writes the device url into *that* copy's
// patch.yml. The profile's cordis.patch.yml is user data and is NOT written on
// install any more, so every URL assertion below targets the bundle. (This file
// used to assert against cordis.patch.yml — the retired Plan A layout — which
// is what produced 6 permanent failures.)
import { execFileSync } from "child_process";
import { existsSync, readFileSync, readdirSync } from "fs";
import { join } from "path";
import { fileURLToPath } from "url";
import { dshHome } from "../utils.js";

const SKILL_DIR = join(fileURLToPath(new URL("..", import.meta.url)));
const INSTALLER = join(SKILL_DIR, "skill-install.mjs");
const HOME = dshHome();
const PLUGIN_DIR = join(HOME, "profiles", "web", "node_modules", "workled");
// Installer output: carries the workled entry and the resolved device url.
const BUNDLE_PATCH = join(PLUGIN_DIR, "patch.yml");
// User-owned profile file: snapshot it, never assert content into it.
const PROFILE_PATCH = join(HOME, "profiles", "web", "cordis.patch.yml");
const TEST_URL = "http://192.168.31.146:18791/mcp";

let pass = 0;
let fail = 0;

function ok(name, cond, detail = "") {
  if (cond) {
    pass++;
    console.log(`  ✔ ${name}`);
  } else {
    fail++;
    console.log(`  ✘ ${name} ${detail ? "— " + detail : ""}`);
  }
}

function run(args) {
  return execFileSync(process.execPath, [INSTALLER, ...args], {
    encoding: "utf8",
    env: { ...process.env, WORKLED_MCP_URL: TEST_URL },
  });
}

// The bundle template quotes `name` ('workled'), so tolerate the quotes.
function bundlePatchHasWorkledRow() {
  if (!existsSync(BUNDLE_PATCH)) return false;
  const text = readFileSync(BUNDLE_PATCH, "utf8");
  return /id:\s*workled\b/.test(text) && /name:\s*['"]?workled['"]?\b/.test(text);
}

function bundlePatchUrl() {
  if (!existsSync(BUNDLE_PATCH)) return null;
  const text = readFileSync(BUNDLE_PATCH, "utf8");
  const m = text.match(/url:\s*['"]?(.+?)['"]?\s*$/m);
  return m ? m[1].trim() : null;
}

function pluginFileExists(rel) {
  return existsSync(join(PLUGIN_DIR, rel));
}

function listDir(dir) {
  if (!existsSync(dir)) return "(not exist)";
  try {
    return readdirSync(dir).join(", ") || "(empty)";
  } catch {
    return "(error)";
  }
}

// cordis.patch.yml belongs to the user's profile, so snapshot it to undo
// uninstall's cleanup pass. The bundle's patch.yml is installer output and is
// regenerated by install, so it needs no snapshot — but note whether the bundle
// was present, so the original install state can be restored at the end.
const origProfilePatch = existsSync(PROFILE_PATCH)
  ? readFileSync(PROFILE_PATCH, "utf8")
  : null;
const origPluginExisted = existsSync(PLUGIN_DIR);

console.log("=== dsh install/uninstall round-trip test (3 cycles) ===");
console.log(`dshHome:       ${HOME}`);
console.log(`pluginDir:     ${PLUGIN_DIR}`);
console.log(`bundlePatch:   ${BUNDLE_PATCH}`);
console.log(`profilePatch:  ${PROFILE_PATCH} ${origProfilePatch === null ? "(absent)" : "(present, snapshotted)"}`);
console.log(`installer:     ${INSTALLER}`);
console.log("");

// Clean slate: uninstall first to start from zero.
console.log("[pre] cleaning slate...");
try { run(["uninstall", "--client", "dsh"]); } catch {}
console.log("");

for (let cycle = 1; cycle <= 3; cycle++) {
  console.log(`--- Cycle ${cycle} ---`);

  // === INSTALL ===
  console.log("  INSTALL:");
  let installOut;
  try {
    installOut = run(["install", "--client", "dsh"]);
    ok("install command exits cleanly", true);
  } catch (e) {
    installOut = e.stdout || "";
    ok("install command exits cleanly", false, e.message);
  }

  // Check install output reports the installed bundle path (dsh uses the
  // "bundle" wording, unlike the plugin-file clients).
  ok("install output reports bundle path", /Installed dsh bundle/.test(installOut), installOut.trim());

  // Check plugin tree
  ok("plugin dir exists", existsSync(PLUGIN_DIR));
  ok("package.json exists", pluginFileExists("package.json"));
  ok("src/index.js exists", pluginFileExists("src/index.js"));
  ok("patch.yml exists", pluginFileExists("patch.yml"));

  // Check the bundle patch — this is where Plan B puts the entry and the url.
  ok("bundle patch has workled row (id + name)", bundlePatchHasWorkledRow());
  const urlInPatch = bundlePatchUrl();
  ok("bundle patch has correct URL", urlInPatch === TEST_URL, `got: ${urlInPatch}`);
  ok("bundle patch url is not the placeholder", !String(urlInPatch).includes("<device-name>"), `got: ${urlInPatch}`);

  // patchBundleUrl() must rewrite the url in place: everything else in the
  // template (comment header, timeout, enabled) has to survive untouched.
  const bundleText = existsSync(BUNDLE_PATCH) ? readFileSync(BUNDLE_PATCH, "utf8") : "";
  ok("in-place rewrite keeps timeout", /timeout:\s*10000/.test(bundleText));
  ok("in-place rewrite keeps enabled", /enabled:\s*true/.test(bundleText));
  ok("in-place rewrite keeps comment header", bundleText.includes("#"));

  // === UNINSTALL ===
  console.log("  UNINSTALL:");
  let uninstallOut;
  try {
    uninstallOut = run(["uninstall", "--client", "dsh"]);
    ok("uninstall command exits cleanly", true);
  } catch (e) {
    uninstallOut = e.stdout || "";
    ok("uninstall command exits cleanly", false, e.message);
  }

  ok("uninstall output mentions plugin dir", uninstallOut.includes("plugin"), uninstallOut.trim());

  // Check no leftovers
  ok("plugin dir removed", !existsSync(PLUGIN_DIR), `still exists: ${listDir(PLUGIN_DIR)}`);
  ok("plugins/ dir cleaned up", !existsSync(join(HOME, "plugins")) || readdirSync(join(HOME, "plugins")).length === 0);
  ok("bundle patch removed with the bundle", !existsSync(BUNDLE_PATCH));
  ok("no node_modules/workled dir leftover", !existsSync(PLUGIN_DIR));

  // The profile patch is the user's file: uninstall may clean workled rows out
  // of it, but must never leave one behind.
  if (existsSync(PROFILE_PATCH)) {
    const text = readFileSync(PROFILE_PATCH, "utf8");
    ok("profile patch has no workled row", !/id:\s*workled\b/.test(text));
  } else {
    ok("profile patch absent (acceptable)", true);
  }

  console.log("");
}

// Restore original state
console.log("[post] restoring original state...");
if (origProfilePatch !== null) {
  try {
    const { writeFileSync, mkdirSync } = await import("fs");
    mkdirSync(join(HOME, "profiles", "web"), { recursive: true });
    writeFileSync(PROFILE_PATCH, origProfilePatch, "utf8");
    console.log("  restored original profile patch file");
  } catch (e) {
    console.log(`  WARN: could not restore profile patch file: ${e.message}`);
  }
} else if (existsSync(PROFILE_PATCH)) {
  // Original had no profile patch file; drop ours if uninstall emptied it.
  const text = readFileSync(PROFILE_PATCH, "utf8").trim();
  if (text === "[]" || text === "") {
    try {
      const { rmSync } = await import("fs");
      rmSync(PROFILE_PATCH, { force: true });
      console.log("  removed empty profile patch file (restored to original: no file)");
    } catch {}
  }
}

// Restore the bundle: the last uninstall cycle removed it, so reinstall it now
// if it was originally installed. The bundle is registered in the web profile's
// package.json, and its patch.yml is regenerated by install.
if (origPluginExisted && !existsSync(PLUGIN_DIR)) {
  try {
    run(["install", "--client", "dsh"]);
    console.log("  reinstalled bundle (was originally installed)");
  } catch (e) {
    console.log(`  WARN: could not reinstall bundle: ${e.message}`);
  }
} else if (!origPluginExisted && existsSync(PLUGIN_DIR)) {
  // Original state had no bundle; clean up any leftover.
  try {
    run(["uninstall", "--client", "dsh"]);
    console.log("  removed bundle (was originally absent)");
  } catch (e) {
    console.log(`  WARN: could not remove bundle: ${e.message}`);
  }
}

console.log("");
console.log(`=== Results: ${pass} passed, ${fail} failed ===`);
process.exit(fail > 0 ? 1 : 0);
